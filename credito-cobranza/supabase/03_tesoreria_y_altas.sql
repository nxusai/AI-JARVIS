-- Sistema de crédito y cobranza · Tesorería y altas (NXUS AI)
--
-- Se corre DESPUÉS de 01_esquema.sql. Se puede volver a correr sin perder nada.
--
-- Tesorería: el dinero de la empresa de punta a punta. Cada caja tiene una clave:
--   ruta:<id>      caja del asesor de esa ruta
--   gerencia:<id>  caja del gerente
--   oficina:<id>   caja fuerte de la oficina
--   banco:<id>     cuenta bancaria de la empresa
--   externo        fuera de la empresa (socios, proveedores, nómina)
-- Cada movimiento sale de una caja y entra a otra. Lo cobrado y lo prestado en
-- ruta se toman de pagos y créditos; aquí van traslados, depósitos, fondeo,
-- ingresos y egresos.
--
-- Altas: los administradores (dueño, dirección y soporte) pueden crear y editar
-- la estructura y activar usuarios. Nadie más escribe desde la página.

-- ---------------------------------------------------------------------------
-- Cuentas bancarias y movimientos de tesorería
-- ---------------------------------------------------------------------------
create table if not exists public.cuentas_bancarias (
  id smallint generated by default as identity primary key,
  banco text not null,
  alias text not null,
  terminacion text,              -- últimos 4 dígitos, nunca la cuenta completa
  activa boolean not null default true,
  es_demo boolean not null default false
);

create table if not exists public.movimientos_tesoreria (
  id bigint generated always as identity primary key,
  fecha date not null,
  tipo text not null check (tipo in ('traslado', 'deposito', 'retiro', 'fondeo', 'ingreso', 'egreso')),
  caja_origen text not null,     -- 'externo' cuando el dinero entra de fuera
  caja_destino text not null,    -- 'externo' cuando el dinero sale de la empresa
  categoria text,
  concepto text,
  monto numeric(14,2) not null check (monto > 0),
  observacion text,
  creado_por uuid references auth.users (id),
  creado timestamptz not null default now(),
  es_demo boolean not null default false,
  check (caja_origen <> caja_destino),
  check (caja_origen ~ '^(ruta|gerencia|oficina|banco):[0-9]+$|^externo$'),
  check (caja_destino ~ '^(ruta|gerencia|oficina|banco):[0-9]+$|^externo$')
);
create index if not exists mov_fecha_idx on public.movimientos_tesoreria (fecha);

-- ---------------------------------------------------------------------------
-- Ámbito de cada usuario (qué parte de la empresa ve)
-- ---------------------------------------------------------------------------
alter table public.perfiles add column if not exists ambito text not null default 'empresa'
  check (ambito ~ '^empresa$|^(region|zona|gerencia|oficina|ruta):[0-9]+$');
alter table public.perfiles add column if not exists correo text;

-- ---------------------------------------------------------------------------
-- Identificadores automáticos para las altas de estructura
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['regiones','zonas','gerencias','oficinas','rutas'] loop
    execute format('create sequence if not exists public.%I_id_seq as smallint owned by public.%I.id', t, t);
    execute format('alter table public.%I alter column id set default nextval(%L)', t, 'public.' || t || '_id_seq');
    execute format('select setval(%L, greatest(coalesce((select max(id) from public.%I), 0), 1))', 'public.' || t || '_id_seq', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Candados
-- ---------------------------------------------------------------------------
create or replace function public.mi_rol() returns text
language sql stable security definer set search_path = public as $$
  select rol from public.perfiles where id = auth.uid() and activo;
$$;

create or replace function public.es_administrador() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.perfiles where id = auth.uid() and activo and rol in ('dueno', 'direccion', 'soporte'));
$$;

do $$
declare t text;
begin
  foreach t in array array['cuentas_bancarias','movimientos_tesoreria'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists leer_activos on public.%I', t);
    -- Si ya se corrió 04_ambito.sql, se respeta su candado por ámbito.
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'leer_ambito') then
      execute format('create policy leer_activos on public.%I for select to authenticated using (public.usuario_activo())', t);
    end if;
  end loop;
  -- Altas y ediciones de estructura y tesorería: sólo administradores
  foreach t in array array['regiones','zonas','gerencias','oficinas','rutas','cuentas_bancarias','movimientos_tesoreria'] loop
    execute format('drop policy if exists alta_admin on public.%I', t);
    execute format('create policy alta_admin on public.%I for insert to authenticated with check (public.es_administrador())', t);
    execute format('drop policy if exists editar_admin on public.%I', t);
    execute format('create policy editar_admin on public.%I for update to authenticated using (public.es_administrador()) with check (public.es_administrador())', t);
  end loop;
end $$;

-- Perfiles: el administrador activa, cambia rol y ámbito. Nadie puede darse
-- a sí mismo más permisos ni tocar la cuenta de soporte salvo soporte.
drop policy if exists editar_perfiles on public.perfiles;
create policy editar_perfiles on public.perfiles for update to authenticated
  using (public.es_administrador() and id <> auth.uid() and (rol <> 'soporte' or public.mi_rol() = 'soporte'))
  with check (public.es_administrador() and rol <> 'soporte');

-- Los empleados no ven la cuenta de soporte; el dueño y soporte sí.
drop policy if exists ver_mi_perfil on public.perfiles;
create policy ver_mi_perfil on public.perfiles for select to authenticated
  using (id = auth.uid() or (public.es_administrador() and (visible_empleados or public.mi_rol() in ('dueno', 'soporte'))));

-- Guardar el correo en el perfil al crear el usuario
create or replace function public.nuevo_perfil() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.perfiles (id, nombre, correo, rol, activo)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nombre', split_part(new.email, '@', 1)),
    new.email,
    case when exists (select 1 from public.perfiles) then 'consulta' else 'dueno' end,
    not exists (select 1 from public.perfiles)
  )
  on conflict (id) do nothing;
  return new;
end $$;
update public.perfiles p set correo = u.email from auth.users u where u.id = p.id and p.correo is null;

-- ---------------------------------------------------------------------------
-- Vista de movimientos para la página
-- ---------------------------------------------------------------------------
create or replace view public.v_movimientos with (security_invoker = true) as
select m.id, m.fecha, m.tipo, m.caja_origen, m.caja_destino, m.categoria, m.concepto, m.monto, m.observacion, m.es_demo
from public.movimientos_tesoreria m
where m.fecha >= current_date - 400;

grant select on public.v_movimientos to authenticated;
revoke all on public.v_movimientos from anon;
