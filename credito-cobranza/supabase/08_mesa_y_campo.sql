-- Lo que agrega (audios y videos de Emmanuel, 18 nov):
--   · «Seguro» se llama ahora «Gastos administrativos» (indicación del abogado).
--   · Mesa de control: comenzar revisión, solicitar corrección, monto autorizado
--     distinto del solicitado, conversación con el asesor.
--   · Autorizar y desembolsar son dos pasos: el crédito nace hasta que el asesor
--     sube el VIDEO DE ENTREGA del cliente (obligatorio).
--   · Renovaciones con excepción (piden más del 20 % sobre el crédito anterior):
--     las autoriza el gerente zonal.
--   · Clientes con ubicación en el mapa (cobro y negocio), celular y observaciones.
--   · Orden de la ruta de cobro y reasignación de clientes a otra ruta.
--   · Modalidad (diario, semanal, quincenal, mensual) y porcentaje por gerencia:
