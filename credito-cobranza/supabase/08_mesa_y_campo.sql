-- ---------------------------------------------------------------------------
-- 8. Ruta: orden de cobro y reasignación de clientes
-- ---------------------------------------------------------------------------
create or replace function public.ordenar_ruta(p_ruta smallint, p_clientes integer[])
returns integer
language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  if not public.tiene_permiso('ordenar_ruta') or p_ruta not in (select public.mis_rutas()) then
    raise exception 'Tu cargo no puede ordenar esta ruta.';
  end if;
  update public.clientes c set orden_ruta = x.i
    from unnest(p_clientes) with ordinality as x(id, i)
   where c.id = x.id and c.ruta_id = p_ruta;
  get diagnostics n = row_count;
  return n;
end $$;

create or replace function public.reasignar_clientes(p_clientes integer[], p_ruta smallint)
returns integer
language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  if not public.tiene_permiso('reasignar_cartera') or p_ruta not in (select public.mis_rutas()) then
    raise exception 'Tu cargo no puede reasignar clientes a esa ruta.';
  end if;
  if exists (select 1 from public.clientes where id = any (p_clientes) and ruta_id not in (select public.mis_rutas())) then
    raise exception 'Algunos clientes no están en tu ámbito.';
  end if;
  update public.clientes set ruta_id = p_ruta, orden_ruta = null where id = any (p_clientes) and ruta_id <> p_ruta;
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.ordenar_ruta(smallint, integer[]), public.reasignar_clientes(integer[], smallint) from public, anon;
grant execute on function public.ordenar_ruta(smallint, integer[]), public.reasignar_clientes(integer[], smallint) to authenticated;

