-- Al capturar: el asesor no fija el porcentaje, los pagos ni nada de la autorización
create or replace function public.antes_de_solicitud() returns trigger
language plpgsql security definer set search_path = public as $$
declare k record;
begin
  select * into k from public.condicion_de(new.ruta_id, new.frecuencia);
  if k.interes_pct is null or not k.activo then
    raise exception 'La modalidad % no está disponible para esta gerencia.', new.frecuencia;
  end if;
  new.interes_pct := k.interes_pct;
  new.num_cuotas := k.num_cuotas;
  if tg_op = 'INSERT' then
    new.monto_autorizado := null; new.autorizado_por := null; new.autorizado := null; new.excepcion := false;
    new.excepcion_por := null; new.desembolsado_por := null; new.desembolsado := null; new.video_path := null;
    new.revision_por := null; new.revision_inicio := null; new.credito_id := null; new.revisado_por := null; new.revisado := null;
  end if;
  return new;
end $$;
