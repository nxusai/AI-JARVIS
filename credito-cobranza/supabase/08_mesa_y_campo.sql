-- ---------------------------------------------------------------------------
-- 6. Mesa de control: revisar, corregir, autorizar (con excepción) y rechazar
-- ---------------------------------------------------------------------------
drop function if exists public.resolver_solicitud(integer, text, text);
create or replace function public.resolver_solicitud(p_id integer, p_estado text, p_motivo text default null, p_monto numeric default null)
returns text
language plpgsql security definer set search_path = public as $$
declare
  s public.solicitudes;
  ant public.creditos;
  v_monto numeric;
  v_tope numeric := 1 + coalesce(public.param('excepcion_pct'), 20) / 100;
  v_zonal boolean;
  v_mesa boolean := public.tiene_permiso('resolver_solicitudes');
  v_final text := p_estado;
begin
  select * into s from public.solicitudes where id = p_id for update;
  if s.id is null then raise exception 'La solicitud no existe.'; end if;
  -- quien autoriza excepciones: zonal (o más arriba) con la ruta dentro de su ámbito
  v_zonal := public.tiene_permiso('autorizar_excepciones') and s.ruta_id in (select public.mis_rutas());
  if p_estado not in ('tomar', 'observada', 'autorizada', 'rechazada', 'cancelada') then raise exception 'Acción no válida.'; end if;
  if s.estado = 'excepcion' then
    if not v_zonal then raise exception 'Esta renovación es una excepción: la autoriza el gerente zonal.'; end if;
  elsif s.estado = 'revision' then
    if not v_mesa then raise exception 'Tu cargo no tiene permiso para resolver solicitudes.'; end if;
  elsif s.estado = 'autorizada' and p_estado = 'cancelada' then
    if not (v_mesa or v_zonal) then raise exception 'Tu cargo no tiene permiso para cancelar solicitudes.'; end if;
  else
    raise exception 'La solicitud no está en revisión.';
  end if;
  if p_estado in ('observada', 'rechazada', 'cancelada') and nullif(trim(coalesce(p_motivo, '')), '') is null then
    raise exception 'Escribe el motivo.';
  end if;

  if p_estado = 'tomar' then
    update public.solicitudes set revision_por = auth.uid(), revision_inicio = now() where id = p_id;
    return 'revision';
  end if;

  if p_estado = 'autorizada' then
    v_monto := coalesce(p_monto, s.monto_autorizado, s.monto);
    if v_monto < 500 then raise exception 'El monto autorizado mínimo es $500.'; end if;
    if s.credito_anterior_id is not null then
      select * into ant from public.creditos where id = s.credito_anterior_id;
      if s.tipo = 'renovacion' and v_monto <= ant.saldo then
        raise exception 'El monto autorizado debe ser mayor a lo que debe el cliente.';
      end if;
      -- Renovación con excepción: más del 20 % sobre el crédito anterior → la decide el zonal
      if s.tipo = 'renovacion' and v_monto > ant.monto * v_tope + 0.01 and not v_zonal then
        v_final := 'excepcion';
      end if;
    end if;
    update public.solicitudes
       set estado = v_final, monto_autorizado = v_monto,
           comentario = coalesce(nullif(trim(coalesce(p_motivo, '')), ''), comentario),
           excepcion = excepcion or v_final = 'excepcion' or s.estado = 'excepcion',
           excepcion_por = case when s.estado = 'excepcion' then auth.uid() else excepcion_por end,
           autorizado_por = case when v_final = 'autorizada' then auth.uid() else autorizado_por end,
           autorizado = case when v_final = 'autorizada' then now() else autorizado end,
           revisado_por = auth.uid(), revisado = now()
     where id = p_id;
    return v_final;
  end if;

  update public.solicitudes
     set estado = p_estado, motivo = trim(p_motivo), revisado_por = auth.uid(), revisado = now()
   where id = p_id;
  return p_estado;
end $$;
revoke all on function public.resolver_solicitud(integer, text, text, numeric) from public, anon;
grant execute on function public.resolver_solicitud(integer, text, text, numeric) to authenticated;

-- ---------------------------------------------------------------------------
-- 7. Desembolso: sólo con el video de entrega del cliente
-- ---------------------------------------------------------------------------
create or replace function public.desembolsar_solicitud(p_id integer, p_video text)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  s public.solicitudes;
  ant public.creditos;
  v_cliente integer;
  v_credito integer;
  v_desc numeric := 0;
  v_monto numeric;
  v_int numeric;
  v_n integer;
  v_seg numeric := coalesce(public.param('seguro_monto'), 150);
  v_fecha date := public.fecha_operativa();
begin
  select * into s from public.solicitudes where id = p_id for update;
  if s.id is null then raise exception 'La solicitud no existe.'; end if;
  if not public.tiene_permiso('desembolsar') or s.ruta_id not in (select public.mis_rutas()) then
    raise exception 'Tu cargo no tiene permiso para desembolsar en esta ruta.';
  end if;
  if s.estado <> 'autorizada' then raise exception 'La solicitud todavía no está autorizada por mesa de control.'; end if;
  if not exists (select 1 from public.documentos d where d.tipo = 'solicitud' and d.entidad_id = p_id and d.path = p_video
                   and d.categoria = 'Video de entrega' and d.mime like 'video/%') then
    raise exception 'Primero graba y sube el video de entrega del cliente.';
  end if;

  v_monto := coalesce(s.monto_autorizado, s.monto);
  v_int := coalesce(s.interes_pct, public.param('interes_pct'), 50);
  v_n := coalesce(s.num_cuotas, public.param('num_cuotas'), 10)::int;

  if s.credito_anterior_id is not null then
    select * into ant from public.creditos where id = s.credito_anterior_id for update;
    v_cliente := ant.cliente_id;
    if s.tipo = 'renovacion' then
      if ant.saldo > 0 and (ant.total_pagar - ant.saldo) < ant.total_pagar * coalesce(public.param('renovacion_pct'), 80) / 100 - 0.01 then
        raise exception 'El crédito anterior todavía no llega al % por ciento de sus pagos.', coalesce(public.param('renovacion_pct'), 80);
      end if;
      v_desc := ant.saldo;
    end if;
    update public.clientes
       set celular = coalesce(s.celular, celular), observaciones = coalesce(s.observaciones, observaciones),
           lat = coalesce(s.lat, lat), lng = coalesce(s.lng, lng), direccion_negocio = coalesce(s.direccion_negocio, direccion_negocio),
           lat_negocio = coalesce(s.lat_negocio, lat_negocio), lng_negocio = coalesce(s.lng_negocio, lng_negocio)
     where id = v_cliente;
  elsif s.cliente_id is not null then
    v_cliente := s.cliente_id;
  else
    insert into public.clientes (codigo, nombre, ruta_id, colonia, telefono, curp, fecha_nacimiento, direccion,
                                 celular, observaciones, lat, lng, direccion_negocio, lat_negocio, lng_negocio)
    values ('C-' || lpad(nextval('public.clientes_id_seq')::text, 5, '0'), s.cliente_nombre, s.ruta_id, s.colonia, s.telefono,
            nullif(upper(trim(coalesce(s.curp, ''))), ''), s.fecha_nacimiento, s.direccion,
            s.celular, s.observaciones, s.lat, s.lng, s.direccion_negocio, s.lat_negocio, s.lng_negocio)
    returning id into v_cliente;
  end if;
  if v_desc >= v_monto then raise exception 'El saldo anterior (%) es mayor que el nuevo crédito.', v_desc; end if;

  insert into public.creditos (cliente_id, monto, total_pagar, cuota, frecuencia, num_cuotas, fecha_inicio, saldo,
                               tipo, credito_anterior_id, descuento_renovacion, entregado, seguro, solicitud_id, creado_por)
  values (v_cliente, v_monto, round(v_monto * (1 + v_int / 100), 2), round(v_monto * (1 + v_int / 100) / v_n, 2), s.frecuencia, v_n, v_fecha,
          round(v_monto * (1 + v_int / 100), 2), s.tipo, s.credito_anterior_id, v_desc, v_monto - v_desc, v_seg, s.id, auth.uid())
  returning id into v_credito;

  if v_desc > 0 then
    insert into public.pagos (credito_id, fecha, monto, tipo) values (s.credito_anterior_id, v_fecha, v_desc, 'liquidacion_renovacion');
  end if;
  if v_seg > 0 then
    insert into public.movimientos_tesoreria (fecha, tipo, caja_origen, caja_destino, categoria, concepto, monto, creado_por)
    values (v_fecha, 'ingreso', 'externo', 'ruta:' || s.ruta_id, 'Gastos administrativos', 'Gastos administrativos · crédito #' || v_credito, v_seg, auth.uid());
  end if;

  update public.solicitudes
     set estado = 'desembolsada', credito_id = v_credito, cliente_id = v_cliente, video_path = p_video,
         desembolsado_por = auth.uid(), desembolsado = now()
   where id = p_id;
  return v_credito;
end $$;
revoke all on function public.desembolsar_solicitud(integer, text) from public, anon;
grant execute on function public.desembolsar_solicitud(integer, text) to authenticated;

