-- Condición vigente para una ruta y modalidad: la de su gerencia si la tiene; si no, la de la empresa
create or replace function public.condicion_de(p_ruta smallint, p_frec text)
returns table (interes_pct numeric, num_cuotas smallint, activo boolean)
language sql stable security definer set search_path = public as $$
  select c.interes_pct, c.num_cuotas, c.activo
  from public.condiciones c
  where c.frecuencia = p_frec
    and (c.gerencia_id is null or c.gerencia_id = (select o.gerencia_id from public.rutas r join public.oficinas o on o.id = r.oficina_id where r.id = p_ruta))
  order by c.gerencia_id nulls last
  limit 1;
$$;

