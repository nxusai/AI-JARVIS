  id integer generated by default as identity primary key,
  gerencia_id smallint references public.gerencias (id),
  frecuencia text not null check (frecuencia in ('diario', 'semanal', 'quincenal', 'mensual')),
  interes_pct numeric(6,2) not null check (interes_pct >= 0 and interes_pct <= 300),
  num_cuotas smallint not null check (num_cuotas between 1 and 400),
  activo boolean not null default true,
  actualizado timestamptz not null default now(),
