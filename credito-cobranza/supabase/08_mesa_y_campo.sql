update storage.buckets
   set file_size_limit = 52428800,
       allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif', 'application/pdf',
                                  'video/mp4', 'video/webm', 'video/quicktime']
 where id = 'expedientes';

-- ---------------------------------------------------------------------------
-- 13. Datos de ejemplo (sólo si existen): estados nuevos y ubicaciones
-- ---------------------------------------------------------------------------
update public.solicitudes set estado = 'autorizada', monto_autorizado = monto, autorizado = now()
 where es_demo and estado = 'aprobada' and credito_id is null;
update public.solicitudes s
   set interes_pct = (select k.interes_pct from public.condicion_de(s.ruta_id, s.frecuencia) k),
       num_cuotas = (select k.num_cuotas from public.condicion_de(s.ruta_id, s.frecuencia) k)
 where s.es_demo and s.interes_pct is null;
update public.clientes
   set lat = round((19.60 + ((id * 7919) % 1000) / 10000.0 - 0.05)::numeric, 6),
       lng = round((-99.05 + ((id * 104729) % 1000) / 10000.0 - 0.05)::numeric, 6)
 where es_demo and lat is null;
do $$
declare c record;
begin
  if exists (select 1 from public.creditos where es_demo)
     and not exists (select 1 from public.solicitudes where es_demo and estado = 'excepcion') then
    select c2.id, c2.monto, cl.nombre, cl.ruta_id, cl.id as cliente_id into c
    from public.creditos c2 join public.clientes cl on cl.id = c2.cliente_id
    where c2.es_demo and c2.saldo > 0 and (c2.total_pagar - c2.saldo) >= c2.total_pagar * 0.8
    order by c2.id limit 1;
    if c.id is not null then
      insert into public.solicitudes (cliente_nombre, ruta_id, monto, estado, creada, tipo, frecuencia, cliente_id, credito_anterior_id, es_demo)
      values (c.nombre, c.ruta_id, round(c.monto * 1.5 / 500) * 500, 'revision', current_date, 'renovacion', 'semanal', c.cliente_id, c.id, true)
      returning id into c.id;
      update public.solicitudes set estado = 'excepcion', monto_autorizado = monto, excepcion = true,
             comentario = 'Mesa: buen historial; pide 50 % más (ejemplo)' where id = c.id;
    end if;
  end if;
end $$;
